#Requires -Version 7.0
<#
.SYNOPSIS
    Lists the data field layouts of the devices with a subscreen (roadmap 7.1) and writes docs/DEVICE-LAYOUTS.md.
.DESCRIPTION
    The simulator descriptor of every device (simulator.json in the local Connect IQ device folder) holds the data
    screen layouts of the device: every layout has its fields with size and the obscured edges, which is what
    DataField.getObscurityFlags() reports to the field. This script takes the manifest products that have a
    subscreen (Instinct and Descent G1 type watches) and prints, per device, the screen, the subscreen rectangle
    and every layout with the field sizes and obscured edges.

    What it cannot give: where exactly the subscreen overlaps a field. The subscreen rectangle is in the
    coordinates of the device image of the simulator, not of the screen, so the overlap has to be looked at in the
    simulator (roadmap 7.1 and 7.4). The output has no machine specific paths or timestamps: a re-run on the same
    SDK gives the same file.
.PARAMETER RepositoryRoot
    The repository root (manifest.xml).
.PARAMETER ConnectIQRoot
    The local Connect IQ folder. Defaults to the SDK Manager location for the current OS.
.PARAMETER OutputPath
    The folder DEVICE-LAYOUTS.md is written to.
.EXAMPLE
    ./tools/Get-DeviceLayouts.ps1
#>
[CmdletBinding(SupportsShouldProcess)]
param(
    [string]$RepositoryRoot = (Resolve-Path -Path (Join-Path -Path $PSScriptRoot -ChildPath '..')).Path,

    [string]$ConnectIQRoot,

    [string]$OutputPath = (Join-Path -Path (Resolve-Path -Path (Join-Path -Path $PSScriptRoot -ChildPath '..')).Path -ChildPath 'docs')
)

$ErrorActionPreference = 'Stop'

if (-not $ConnectIQRoot) {
    $ConnectIQRoot = if ($IsWindows) {
        Join-Path -Path $env:APPDATA -ChildPath 'Garmin/ConnectIQ'
    }
    elseif ($IsMacOS) {
        Join-Path -Path $HOME -ChildPath 'Library/Application Support/Garmin/ConnectIQ'
    }
    else {
        Join-Path -Path $HOME -ChildPath '.Garmin/ConnectIQ'
    }
}

$DevicesRoot = Join-Path -Path $ConnectIQRoot -ChildPath 'Devices'
$ManifestText = Get-Content -LiteralPath (Join-Path -Path $RepositoryRoot -ChildPath 'manifest.xml') -Raw
$Products = @([regex]::Matches($ManifestText, 'iq:product id="([^"]+)"') | ForEach-Object { $_.Groups[1].Value } | Sort-Object -Unique)
$SdkVersion = (Get-Content -LiteralPath (Join-Path -Path $RepositoryRoot -ChildPath '.ciq-sdk-version') -Raw).Trim()

$Lines = [System.Collections.Generic.List[string]]::new()
$Lines.Add('# Data field layouts of the devices with a subscreen (roadmap 7.1)')
$Lines.Add('')
$Lines.Add("Generated by ``tools/Get-DeviceLayouts.ps1`` from the simulator descriptors of SDK $SdkVersion. Do not edit by hand.")
$Lines.Add('')
$Lines.Add('The subscreen is the small round display inside the main display of these watches. The field does not know about it: it only gets the size of its draw context and the obscured edges (`DataField.getObscurityFlags()`). The simulator lists the obscured edges per field below. The rectangle of the subscreen is given in the coordinates of the simulator device image, not of the screen, so **where the subscreen overlaps a field is not in this file**: that needs a look in the simulator (roadmap 7.1, 7.4).')
$Lines.Add('')

$Found = 0
foreach ($Product in $Products) {
    $SimulatorPath = Join-Path -Path $DevicesRoot -ChildPath "$Product/simulator.json"
    $CompilerPath = Join-Path -Path $DevicesRoot -ChildPath "$Product/compiler.json"
    if (-not (Test-Path -LiteralPath $SimulatorPath)) {
        throw "No simulator.json for '$Product' in '$DevicesRoot'. Download the device with the SDK Manager: a partial install would leave devices out of the list."
    }

    $Simulator = Get-Content -LiteralPath $SimulatorPath -Raw -Encoding utf8 | ConvertFrom-Json
    if (-not $Simulator.subscreen) {
        continue
    }

    $Found++
    $Compiler = Get-Content -LiteralPath $CompilerPath -Raw -Encoding utf8 | ConvertFrom-Json
    $Location = $Simulator.subscreen.location
    $Lines.Add("## $Product")
    $Lines.Add('')
    $Lines.Add("- Screen: $($Compiler.resolution.width) x $($Compiler.resolution.height), shape $($Simulator.display.shape).")
    $Lines.Add("- Subscreen (simulator image coordinates): $($Location.width) x $($Location.height) at x $($Location.x), y $($Location.y).")
    $Lines.Add('')
    $Lines.Add('| Layout | Fields (width x height, obscured edges) |')
    $Lines.Add('|---|---|')
    foreach ($Layout in $Simulator.layouts[0].datafields.datafields) {
        $FieldTexts = foreach ($Field in $Layout.fields) {
            $Obscured = if ($Field.obscurity) { $Field.obscurity -join '/' } else { 'none' }
            "$($Field.location.width) x $($Field.location.height) ($Obscured)"
        }
        $Lines.Add("| $($Layout.name) | $($FieldTexts -join '; ') |")
    }
    $Lines.Add('')
}

if ($Found -eq 0) {
    throw 'No manifest product with a subscreen found. Download the devices with the SDK Manager first.'
}

$OutputFile = Join-Path -Path $OutputPath -ChildPath 'DEVICE-LAYOUTS.md'
if ($PSCmdlet.ShouldProcess($OutputFile, "Write the layouts of $Found devices")) {
    Set-Content -LiteralPath $OutputFile -Value ($Lines -join "`n") -Encoding utf8
}

"$Found devices with a subscreen listed." | Write-Output
